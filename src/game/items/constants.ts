// Creature Samples (Adam, 2026-10-15): one item per species —
// something from the original creature, shed by the living or
// left by the dead, and the heart of every vat recipe. Their
// definitions are GENERATED from the species table so a species
// and its sample can never drift apart; the static record below
// merges them in.
const SAMPLE_ITEM_DEFS = Object.fromEntries(
  Object.values(SPECIES).map((def) => [
    `sample_${def.id}`,
    {
      id: `sample_${def.id}` as ItemId,
      name: `${def.name} Sample`,
      category: 'raw',
      description: `Something from a living ${def.name} — a viable cutting, shed and gathered. The Culture Vat can grow the creature from it, once.`,
      iconName: 'Dna',
      color: '#84cc16',
      rarity: 'uncommon',
      maxStack: 10,
    } as ItemDef,
  ]),
) as Record<`sample_${FaunaSpecies}`, ItemDef>;

// Propagule Seeds (Adam's planting ruling, 2026-10-18): one
// seed item per seed-bearing flora species — GENERATED from
// the flora table off each def's `propagation: 'seed'` field,
// the samples pattern, so a species and its seed can never
// drift apart. Fungi bear spores in name. The six original
// hand-written seed defs (lantern fern, sap weaver, petal
// mill, snap trap, bell bloom, bounce shroom) keep their
// bespoke copy: the hand-written entries sit AFTER this
// spread in ITEMS and win their keys.
const SEED_ITEM_DEFS = Object.fromEntries(
  Object.values(FLORA)
    .filter((def) => def.propagation === 'seed')
    .map((def) => [
      `seed_${def.id}`,
      {
        id: `seed_${def.id}` as ItemId,
        // Fungi and ferns bear spores; everything else, seeds —
        // the lantern fern's hand-written "Spore" set the taste.
        name: `${def.name} ${def.kind === 'fungus' || def.id.includes('fern') ? 'Spores' : 'Seeds'}`,
        category: 'seed',
        description: def.kind === 'fungus' || def.id.includes('fern')
          ? `Spores of the ${def.name} — plant them where its kind takes hold, and it rises again.`
          : `Seeds of the ${def.name} — plant them where its kind takes hold, and it rises again.`,
        iconName: def.kind === 'fungus' ? 'Sparkles' : 'Sprout',
        color: '#4ade80',
        rarity: 'common',
        maxStack: 99,
      } as ItemDef,
    ]),
) as Record<`seed_${FloraSpecies}`, ItemDef>;

